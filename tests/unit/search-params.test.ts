import { describe, expect, it } from "vitest";
import { one, pageNumber } from "@/lib/routes/search-params";

/**
 * معاملات الاستعلام — تصل من **عنوان يكتبه المستخدم بيده**.
 *
 * ── 🔴 العيب الذي كُشف بالتدقيق ─────────────────────────────────────
 * أربع صفحات كانت تحسب الصفحة بـ`Number(v ?? 1) || 1`. و`||` يردّ
 * **الصفر وحده**، والسالب صادق منطقياً — فـ`?page=-3` كان يمرّ كما هو،
 * فيصير `skip` سالباً وتخرج رسالة خطأ خام من القاعدة في وجه المستخدم.
 *
 * والكسر يمرّ كذلك: `?page=1.5` يُنتج `skip` كسرياً.
 */

describe("one — قيمة نصّية واحدة", () => {
  it("يُرجع النصّ كما هو", () => {
    expect(one("مسكونة")).toBe("مسكونة");
  });

  it("⚠️ الفراغ غيابٌ لا قيمة", () => {
    // `?q=` يصل نصّاً فارغاً؛ تمريره مرشّحاً يُفرغ القائمة بلا سبب ظاهر
    expect(one("")).toBeUndefined();
  });

  it("⚠️ المصفوفة تُرفض ولا يُؤخذ أوّلها", () => {
    // `?status=A&status=B` صالح في العنوان. واختيار الأوّل ضمناً قرارٌ
    // لا يعرفه القارئ، وأسوأ من ألّا يُرشَّح شيء.
    expect(one(["A", "B"])).toBeUndefined();
  });

  it("الغياب يبقى غياباً", () => {
    expect(one(undefined)).toBeUndefined();
  });
});

describe("pageNumber — رقم صفحة صالح", () => {
  it("يقرأ الرقم الصحيح", () => {
    expect(pageNumber("3")).toBe(3);
  });

  it("الغياب يعني الصفحة الأولى", () => {
    expect(pageNumber(undefined)).toBe(1);
  });

  it("🔴 السالب يُردّ إلى 1 — وكان يمرّ", () => {
    expect(pageNumber("-3")).toBe(1);
  });

  it("🔴 الكسر يُردّ إلى 1 — وكان يمرّ", () => {
    expect(pageNumber("1.5")).toBe(1);
  });

  it("الصفر يُردّ إلى 1", () => {
    expect(pageNumber("0")).toBe(1);
  });

  it("النصّ غير الرقمي يُردّ إلى 1", () => {
    expect(pageNumber("abc")).toBe(1);
  });

  it("المصفوفة تُردّ إلى 1", () => {
    expect(pageNumber(["2", "5"])).toBe(1);
  });
});
