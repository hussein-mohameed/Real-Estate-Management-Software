import { config as loadEnv } from "dotenv";

/**
 * ═══════════════════════════════════════════════════════════════════════
 *  حارس بيئة اختبارات التكامل — يعمل قبل أي ملفّ اختبار.
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ── 🔴 ما يمنعه ─────────────────────────────────────────────────────
 * اختبارات التكامل تكتب بيانات تُلتزَم فعلاً، وتنظّفها بعدها **بتعطيل
 * محفِّز `append-only` على الدفتر**. أي أنها تملك قدرةَ محوٍ لا يملكها
 * التطبيق نفسه.
 *
 * وحين تشترك مع التطوير في مخطّط واحد، فأوّل تشغيل بعد إدخال بيانات
 * مجمَّعٍ حقيقي يمحوها. لم يحدث — لأنه لم تكن هناك بيانات حقيقية بعد.
 * وهذا الملفّ يجعله **مستحيلاً** لا مستبعَداً.
 *
 * ── ⚠️ ولماذا `setupFiles` لا سطرٌ في `helpers.ts` ──────────────────
 * ‏ESM يُقيّم كل `import` قبل أي عبارة في جسم الوحدة. فسطر تحميلٍ في
 * `helpers.ts` يعمل **بعد** استيراد `@/lib/prisma` في ملفّ الاختبار،
 * وترتيبُ ذلك يتغيّر بتغيّر ترتيب الاستيرادات — أي أن الحارس يعمل أو لا
 * يعمل بحسب تفصيلٍ لا يلاحظه أحد. `setupFiles` يعمل قبل كل شيء دائماً.
 *
 * ── وترتيب الملفّات ────────────────────────────────────────────────
 * `.env.test` **أولاً**: `dotenv` لا يكتب فوق متغيّر مضبوط، فالأوّل يفوز.
 */

loadEnv({ path: [".env.test", ".env.local", ".env"], quiet: true });

const schema = process.env["DB_SCHEMA"];

if (!schema || schema === "public") {
  throw new Error(
    [
      "🔴 اختبارات التكامل ترفض العمل على مخطّط التطوير.",
      "",
      `المخطّط الحالي: ${schema ?? "غير مضبوط (أي public)"}`,
      "",
      "هذه الاختبارات تكتب بياناتٍ تُلتزَم، وتنظّفها بتعطيل محفِّز",
      "append-only على الدفتر. على مخطّط التطوير يعني ذلك محو بياناتك.",
      "",
      "الإعداد يُشغَّل مرّة واحدة:",
      "  npx tsx --env-file=.env.local scripts/setup-test-schema.ts",
      "  npx cross-env USE_TEST_SCHEMA=1 prisma migrate deploy",
      "  npx cross-env USE_TEST_SCHEMA=1 DB_SCHEMA=integration_test tsx scripts/apply-constraints.ts",
    ].join("\n"),
  );
}

