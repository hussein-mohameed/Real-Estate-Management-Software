/**
 * ═══════════════════════════════════════════════════════════════════════
 *  معاملات الاستعلام في صفحات القوائم.
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ── لماذا موضع واحد ────────────────────────────────────────────────
 * كان هذا النوع وهذه الدالّة مكرَّرين حرفياً في ستّ صفحات: الشقق والعقود
 * والسكان والخدمات والموظفون والاشتراكات. ونسخةٌ سادسة من قاعدة تحويل
 * واحدة تعني ستّة مواضع يجب أن تتغيّر معاً، وأوّل مرّة يُنسى أحدها يظهر
 * الفرق كسلوك ترشيح مختلف في شاشة واحدة — وهو أصعب ما يُلاحَظ.
 *
 * ── ⚠️ ولماذا لا `PageProps<"/…">` ─────────────────────────────────
 * أنواع المسارات يولّدها Next **عند البناء**. فمسارٌ جديد لا يُصرَّف حتى
 * أوّل بناء، ويكسر `typecheck` قبله بلا أن يكون في الكود عيب. حدث ذلك
 * فعلاً عند إضافة `/admin/subscriptions`.
 */

/**
 * ما يصل من `searchParams`.
 *
 * ⚠️ القيمة قد تكون **مصفوفة**: `?status=A&status=B` صالح في العنوان،
 * ويصل `string[]`. ونوعٌ يقول `string` وحده يمرّ في التصريف ثم ينكسر
 * في وقت التشغيل على عنوان يكتبه المستخدم بيده.
 */
export type SearchParams = Record<string, string | string[] | undefined>;

/**
 * قيمة نصّية واحدة، أو `undefined`.
 *
 * ⚠️ **والفراغ يُعامَل غيابَاً.** `?q=` يصل نصّاً فارغاً، وتمريرُه مرشّحاً
 * يُنتج بحثاً عن لا شيء فتفرغ القائمة بلا سبب ظاهر. والمصفوفة تُرفض بدل
 * أن يُؤخَذ أوّلُ عنصرها: اختيارٌ ضمنيّ من قيمتين لا يعرفه القارئ.
 */
export function one(value: string | string[] | undefined): string | undefined {
  return typeof value === "string" && value !== "" ? value : undefined;
}

/**
 * رقم صفحة صالح — واحدٌ على الأقل.
 *
 * ⚠️ يحرس ثلاث حالات تصل من عنوان مكتوب بيد: `?page=abc` (‏`NaN`)،
 * و`?page=0`، و`?page=-3`. أيّها بلا حرس يُنتج `skip` سالباً أو `NaN`
 * فيرمي الاستعلام خطأً خاماً في وجه المستخدم.
 */
export function pageNumber(value: string | string[] | undefined): number {
  const parsed = Number(one(value) ?? 1);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : 1;
}
