import { cn } from "@/lib/cn";

/**
 * عزل مقطع لاتيني/رقمي داخل نصّ عربي.
 *
 * ── العيب الذي يعالجه ────────────────────────────────────────────────
 * خوارزمية النصّ ثنائي الاتجاه (‏Unicode Bidi) تعامل كل مجموعة أرقام
 * كمقطع LTR مستقل، ثم ترتّب **المقاطع** بحسب اتجاه الفقرة. فداخل صفحة
 * RTL يظهر:
 *     `0770 123 4567`   ←  4567 123 0770   ✗
 *     `25/08/2026 13:31` ←  13:31 25/08/2026 ✗
 * الرقم مخزَّن ومُنسَّق صحيحاً، **ويُعرض مقلوباً**.
 *
 * `dir="ltr"` وحده لا يكفي: يجب أيضاً **عزل** المقطع بـ`unicode-bidi: isolate`
 * وإلا تسرّب أثره إلى ما حوله.
 *
 * ⚠️ **يُستعمل لكل** رقم هاتف · تاريخ · وقت · رقم فاتورة أو عقد أو طلب ·
 * لوحة سيارة · معرّف. أي سلسلة فيها فواصل أو شرطات ومقاطع متعدّدة.
 * المبلغ **لا يحتاجه** لأن `<Money>` مقطع واحد بلا فواصل بيضاء.
 */
export function Ltr({
  children,
  className,
}: {
  children: React.ReactNode;
  className?: string;
}) {
  return (
    <span dir="ltr" className={cn("inline-block [unicode-bidi:isolate]", className)}>
      {children}
    </span>
  );
}
